/**
 * Writes the REST contract the client is built from: the OpenAPI document and the
 * id the server stamps on every answer. `bun run api:generate` runs this, then
 * tools/api-types turns the document into path types.
 */
import { resolve } from "node:path";

import { contractId, openApiDocument } from "../src/openapi";

const apiDir = resolve(import.meta.dirname, "../../client/src/api");
const document = openApiDocument();

await Bun.write(resolve(apiDir, "openapi.json"), `${JSON.stringify(document, null, "\t")}\n`);
await Bun.write(
	resolve(apiDir, "contract.gen.ts"),
	[
		"/** Generated by `bun run api:generate`. Do not edit. */",
		"",
		`export const CONTRACT_ID = "${contractId(document)}";`,
		"",
	].join("\n"),
);
