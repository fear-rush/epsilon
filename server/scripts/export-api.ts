/**
 * Writes the REST contract the client is built from: the OpenAPI document, the
 * path and schema types generated from it, and the id the server stamps on every
 * answer. `bun run api:generate` runs this.
 */
import { resolve } from "node:path";

import { contractId, openApiDocument } from "../src/openapi";
import { renderApiTypes } from "../src/openapi-types";

const apiDir = resolve(import.meta.dirname, "../../client/src/api");
const document = openApiDocument();
const documentJson = `${JSON.stringify(document, null, "\t")}\n`;

await Bun.write(resolve(apiDir, "openapi.json"), documentJson);
await Bun.write(resolve(apiDir, "schema.gen.ts"), renderApiTypes(documentJson));
await Bun.write(
	resolve(apiDir, "contract.gen.ts"),
	[
		"/** Generated by `bun run api:generate`. Do not edit. */",
		"",
		`export const CONTRACT_ID = "${contractId(document)}";`,
		"",
	].join("\n"),
);
